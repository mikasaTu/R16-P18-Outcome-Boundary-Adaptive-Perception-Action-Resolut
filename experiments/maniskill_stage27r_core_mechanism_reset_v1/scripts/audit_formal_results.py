from common import PROTOCOL_ID, atomic_json, sha256_file

PREDECESSORS = ("experiments/maniskill_act_boundary_screen_v1", "experiments/maniskill_stage25_repair_oracle_v1", "experiments/maniskill_stage26_counterfactual_completion_v1")
WEIGHTS = {"balanced": (100, 20, 5, -10, -5), "success_dominant": (120, 10, 3, -12, -6), "progress_dominant": (80, 35, 5, -10, -5)}
ACCOUNTING = {"global_encoder_calls", "fine_encoder_calls", "policy_forward_calls", "policy_forward_rows", "visual_tokens", "action_opportunities", "executed_steps", "gpu_latency_ms", "simulator_latency_ms", "estimated_flops", "peak_memory_bytes", "selector_latency_ms", "episode_total_compute"}
DEPLOYABLE_MODEL_INPUT_KEYS = frozenset({"state", "rgb", "_visual_mode", "_tile_id", "_tile_grid"})
# This key is generated by ``compute_loss`` and consumed only to reuse one
# ACT posterior sample across the fine/coarse consistency branches.  It is not
# supplied by the environment or by the inference path.  Keep this allowlist
# explicit: any other unknown observation/data key remains a hard failure.
TRAINING_INTERNAL_MODEL_INPUT_KEYS = {
    "_latent_noise": "ACT posterior sample generated inside compute_loss; training-only stochastic control, never an environment/inference input",
}
TRAINING_INTERNAL_USE_FUNCTIONS = frozenset({"compute_loss", "forward"})
derived_names = {
    "INDEPENDENT_AUDIT.json",
    "POSTHOC_INDEPENDENT_AUDIT.json",
    "FORMAL_COMPLETE.json",
}
OFFICIAL_MANIFEST_METADATA = frozenset(derived_names)


def _model_input_key_uses(model_text: str) -> tuple[list[tuple[str, str | None]], list[dict]]:
    """Extract literal and dynamic observation/data key uses.

    The previous audit only handled ``obs[\"key\"]`` and therefore missed the
    explicit ``obs.get(\"_latent_noise\")`` training control.  Both forms are
    intentionally handled here.  Dynamic keys are reported explicitly and
    fail closed because a static allowlist cannot classify their runtime value.
    """
    tree = ast.parse(model_text)
    parents: dict[ast.AST, ast.AST] = {}
    for parent in ast.walk(tree):
        for child in ast.iter_child_nodes(parent):
            parents[child] = parent

    def enclosing_function(node: ast.AST) -> str | None:
        current = parents.get(node)
        while current is not None:
            if isinstance(current, (ast.FunctionDef, ast.AsyncFunctionDef)):
                return current.name
            current = parents.get(current)
        return None

    uses: list[tuple[str, str | None]] = []
    dynamic_accesses: list[dict] = []
    for node in ast.walk(tree):
        key: str | None = None
        owner: ast.AST | None = None
        if (
            isinstance(node, ast.Subscript)
            and isinstance(node.value, ast.Name)
            and node.value.id in {"obs", "data"}
        ):
            owner = node
            if isinstance(node.slice, ast.Constant) and isinstance(node.slice.value, str):
                key = node.slice.value
            else:
                dynamic_accesses.append(
                    {
                        "function": enclosing_function(node) or "<module>",
                        "line": int(node.lineno),
                        "form": "subscript",
                        "object": node.value.id,
                        "expression": ast.unparse(node.slice),
                    }
                )
        elif (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Attribute)
            and node.func.attr == "get"
            and isinstance(node.func.value, ast.Name)
            and node.func.value.id in {"obs", "data"}
        ):
            owner = node
            if node.args and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str):
                key = node.args[0].value
            else:
                expression = ast.unparse(node.args[0]) if node.args else "<missing>"
                dynamic_accesses.append(
                    {
                        "function": enclosing_function(node) or "<module>",
                        "line": int(node.lineno),
                        "form": "get",
                        "object": node.func.value.id,
                        "expression": expression,
                    }
                )
        if key is not None and owner is not None:
            uses.append((key, enclosing_function(owner)))
    return uses, sorted(
        dynamic_accesses,
        key=lambda row: (row["line"], row["function"], row["form"], row["object"]),
    )


def classify_model_input_keys(model_text: str) -> dict:
    """Classify static model keys while preserving a fail-closed unknown check."""
    uses, dynamic_accesses = _model_input_key_uses(model_text)
    observed = {key for key, _ in uses}
    training_internal = observed.intersection(TRAINING_INTERNAL_MODEL_INPUT_KEYS)
    deployable = observed.difference(training_internal)
    unknown = deployable.difference(DEPLOYABLE_MODEL_INPUT_KEYS)
    internal_violations = sorted(
        f"{key}@{function or '<module>'}"
        for key, function in uses
        if key in training_internal and function not in TRAINING_INTERNAL_USE_FUNCTIONS
    )
    return {
        "pass": not unknown and not internal_violations and not dynamic_accesses,
        # Keep this field for existing consumers; it now includes .get uses.
        "observed_keys": sorted(observed),
        "deployable_observed_keys": sorted(deployable),
        "training_internal_keys": sorted(training_internal),
        "unknown_keys": sorted(unknown),
        "training_internal_violations": internal_violations,
        "dynamic_accesses": dynamic_accesses,
        "training_internal_rationale": {
            key: TRAINING_INTERNAL_MODEL_INPUT_KEYS[key]
            for key in sorted(training_internal)
        },
    }


def official_scientific_manifest(formal_root: Path, output: Path) -> list[dict]:
    """Return the stable scientific-input manifest for a formal root.

    Statistics, mechanism and result evidence are scientific derived inputs
    and remain covered.  The independent audits, completion marker, and
    interrupted/resume temporary files are process metadata and are excluded
    so rerunning an audit cannot change the manifest it reports.
    """
    root = Path(formal_root).resolve()
    output_path = Path(output).resolve()
    files = sorted(
        path
        for path in root.rglob("*")
        if path.is_file()
        and path.resolve() != output_path
        and path.name not in OFFICIAL_MANIFEST_METADATA
        and ".resume-" not in path.name
        and ".tmp-" not in path.name
    )
    return [
        {
            "path": str(path.relative_to(root)),
            "sha256": sha256_file(path),
            "bytes": path.stat().st_size,
        }
        for path in files
    ]


def frozen_preregistration_digest(repo: Path, experiment: Path) -> dict:
    """Verify preregistration against the frozen Git snapshot, without editing it.

    PROTOCOL_FREEZE.json was intentionally kept minimal and may not contain a
    digest field.  In that case the protocol's predecessor-freeze manifest
    supplies the immutable Git head from which the preregistration bytes are
    derived.  A missing/invalid Git snapshot is a failed check, never a pass.
    """
    protocol = json.loads((experiment / "PROTOCOL_FREEZE.json").read_text())
    current = sha256_file(experiment / "preregistration.yaml")
    expected = protocol.get("preregistration_sha256")
    if expected is not None:
        return {"pass": expected == current, "digest_field_present": True, "expected": expected, "observed": current}
    manifest_path = experiment / "manifests/predecessor_tree_freeze.json"
    try:
        manifest = json.loads(manifest_path.read_text())
        frozen_head = str(manifest["head"])
        prereg_path = str(protocol["preregistration_path"])
        frozen_bytes = subprocess.check_output(["git", "show", f"{frozen_head}:{prereg_path}"], cwd=repo)
        frozen_digest = __import__("hashlib").sha256(frozen_bytes).hexdigest()
        return {
            "pass": frozen_digest == current,
            "digest_field_present": False,
            "expected": frozen_digest,
            "observed": current,
            "derived_from_frozen_git_commit": frozen_head,
            "derived_path": prereg_path,
        }
    except (KeyError, OSError, subprocess.CalledProcessError, ValueError) as exc:
        return {
            "pass": False,
            "digest_field_present": False,
            "expected": None,
            "observed": current,
            "derived_from_frozen_git_commit": None,
            "error": f"cannot derive preregistration from frozen Git snapshot: {exc}",
        }


def final_verifier_source(repo: Path, audit_script: Path) -> dict:
    """Bind the audit result to the exact clean source that produced it."""
    repo = Path(repo).resolve()
    audit_script = Path(audit_script).resolve()
    dirty = subprocess.check_output(
        ["git", "status", "--porcelain"], cwd=repo, text=True
    ).strip()
    commit = subprocess.check_output(
        ["git", "rev-parse", "HEAD"], cwd=repo, text=True
    ).strip()
    tree = subprocess.check_output(
        ["git", "rev-parse", "HEAD^{tree}"], cwd=repo, text=True
    ).strip()
    try:
        script_path = str(audit_script.relative_to(repo))
    except ValueError:
        script_path = str(audit_script)
    return {
        "pass": not dirty,
        "role": "final_independent_verifier",
        "commit": commit,
        "tree": tree,
        "repository": str(repo),
        "audit_script": script_path,
        "audit_script_sha256": sha256_file(audit_script),
        "working_tree_clean": not dirty,
        "dirty_entries": dirty.splitlines(),
    }


def validate_lineage_role_separation(
    lineage: dict,
    registry_resolved: dict,
    terminal: dict,
    current_verifier: dict,
    terminal_getjob: dict | None = None,
    registry_placement: dict | None = None,
) -> dict:
    """Validate historical v11 production and later final-verifier roles.

    This intentionally does not compare the historical
    ``posthoc_verifier_source`` to the current HEAD.  The former is the exact
    v11 continuation source that created the snapshot/lineage; the latter is a
    later independent verifier whose source is self-bound in this audit.
    """
    errors: list[str] = []

    def require(condition: bool, message: str) -> None:
        if not condition:
            errors.append(message)

    continuation = lineage.get("continuation_registry", {})
    historical = lineage.get("posthoc_verifier_source", {})
    resolved_evidence = registry_resolved.get("evidence", {})
    terminal_source = terminal.get("source", {})
    terminal_registry = terminal.get("registry", {})
    terminal_active = terminal.get("active_job_verification", {}).get("v11", {})

    run_id = continuation.get("run_id")
    job_id = continuation.get("job_id")
    source_commit = continuation.get("source_commit")
    source_tree = continuation.get("source_tree")

    require(lineage.get("protocol_id") == PROTOCOL_ID, "lineage protocol mismatch")
    require(lineage.get("status") == "PASS", "lineage status is not PASS")
    require(continuation.get("status") == "PASS", "continuation registry status is not PASS")
    require(bool(run_id and job_id and source_commit and source_tree), "lineage continuation identity is incomplete")
    require(registry_resolved.get("run_id") == run_id, "v11 registry run_id mismatch")
    require(resolved_evidence.get("source_commit") == source_commit, "v11 registry source commit mismatch")
    require(resolved_evidence.get("source_tree") == source_tree, "v11 registry source tree mismatch")

    require(
        historical.get("role") == "clean_posthoc_verifier_and_continuation_source",
        "historical verifier role mismatch",
    )
    require(historical.get("commit") == source_commit, "historical verifier commit mismatch")
    require(historical.get("tree") == source_tree, "historical verifier tree mismatch")
    require(historical.get("pai_run_id") == run_id, "historical verifier run_id mismatch")
    require(historical.get("pai_job_id") == job_id, "historical verifier job_id mismatch")

    require(terminal.get("protocol_id") == PROTOCOL_ID, "v11 terminal protocol mismatch")
    require(terminal.get("status") == "PASS", "v11 terminal evidence status is not PASS")
    require(terminal.get("terminal") is True, "v11 terminal flag is not true")
    require(terminal.get("terminal_status") == "Stopped", "v11 terminal status is not Stopped")
    require(terminal.get("no_overlap_after_terminal") is True, "v11 terminal no-overlap flag is not true")
    require(terminal.get("run_id") == run_id, "v11 terminal run_id mismatch")
    require(terminal.get("job_id") == job_id, "v11 terminal job_id mismatch")
    require(terminal_source.get("commit") == source_commit, "v11 terminal source commit mismatch")
    require(terminal_source.get("tree") == source_tree, "v11 terminal source tree mismatch")
    require(
        terminal_registry.get("resolved") == continuation.get("files", {}).get("resolved"),
        "v11 terminal registry resolved binding mismatch",
    )
    require(
        terminal_registry.get("placement") == continuation.get("files", {}).get("placement"),
        "v11 terminal registry placement binding mismatch",
    )
    require(terminal_active.get("job_id") == job_id, "v11 active-verification job_id mismatch")
    require(terminal_active.get("live_status") == "Stopped", "v11 active-verification status mismatch")
    require(terminal_active.get("active") is False, "v11 active-verification still reports active")
    if terminal_getjob is None:
        errors.append("v11 raw terminal GetJob is missing")
    else:
        require(terminal_getjob.get("JobId") == job_id, "v11 raw GetJob job_id mismatch")
        require(terminal_getjob.get("Status") == "Stopped", "v11 raw GetJob status mismatch")
        raw_run_id = terminal_getjob.get("Settings", {}).get("Tags", {}).get("run_id")
        require(raw_run_id == run_id, "v11 raw GetJob run_id mismatch")
    if registry_placement is None:
        errors.append("v11 registry placement evidence is missing")
    else:
        require(registry_placement.get("run_id") == run_id, "v11 placement run_id mismatch")
        require(registry_placement.get("job_id") == job_id, "v11 placement job_id mismatch")

    require(current_verifier.get("pass") is True, "final verifier source is not clean")
    require(
        current_verifier.get("role") == "final_independent_verifier",
        "final verifier role mismatch",
    )
    require(
        historical.get("role") != current_verifier.get("role"),
        "historical and final verifier roles are not separated",
    )
    return {
        "pass": not errors,
        "errors": errors,
        "historical_continuation_verifier": {
            "role": historical.get("role"),
            "commit": source_commit,
            "tree": source_tree,
            "run_id": run_id,
            "job_id": job_id,
        },
        "final_independent_verifier": current_verifier,
        "same_source_commit": historical.get("commit") == current_verifier.get("commit"),
        "role_separation_semantics": "v11 created/validated continuation lineage; current clean source performs the final independent audit",
    }


def _load_bound_json(path: Path, binding: dict | None = None) -> tuple[dict, dict]:
    """Load JSON and, when supplied, verify its recorded path/hash/size."""
    path = Path(path).resolve()
    if not path.is_file():
        raise RuntimeError(f"missing evidence file: {path}")
    observed = {"path": str(path), "sha256": sha256_file(path), "bytes": path.stat().st_size}
    if binding is not None:
        recorded_path = Path(str(binding.get("path", ""))).resolve()
        if recorded_path != path:
            raise RuntimeError(f"evidence path mismatch: {path} != {recorded_path}")
        if binding.get("sha256") != observed["sha256"] or binding.get("bytes") != observed["bytes"]:
            raise RuntimeError(f"evidence hash/bytes mismatch: {path}")
    return json.loads(path.read_text(encoding="utf-8")), observed


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo", type=Path, required=True)
    parser.add_argument("--formal-root", type=Path, required=True)
    parser.add_argument("--training-root", type=Path, required=True)
    parser.add_argument("--dataset-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--lineage-manifest", type=Path, default=None)
    parser.add_argument("--v11-registry-resolved", type=Path, default=None)
    parser.add_argument("--v11-terminal", type=Path, default=None)
    args = parser.parse_args()
    checks = {}
    experiment = args.repo / "experiments/maniskill_stage27r_core_mechanism_reset_v1"
    freeze = json.loads((experiment / "manifests/predecessor_tree_freeze.json").read_text())["trees"]
    current = {path: subprocess.check_output(["git", "rev-parse", f"HEAD:{path}"], cwd=args.repo, text=True).strip() for path in PREDECESSORS}
    checks["predecessor_immutability"] = {"pass": current == freeze, "frozen": freeze, "current": current}
    verifier = final_verifier_source(args.repo, Path(__file__))
    checks["clean_source_commit"] = verifier
    checks["final_verifier_source"] = dict(verifier)
    checks["protocol_freeze"] = frozen_preregistration_digest(args.repo, experiment)

    lineage_path = args.lineage_manifest or args.formal_root / "ORACLE_LINEAGE_MANIFEST.json"
    terminal_path = args.v11_terminal or args.formal_root / "CONTINUATION_V11_TERMINAL_VALID.json"
    try:
        lineage, lineage_binding = _load_bound_json(lineage_path)
        recorded_resolved = lineage.get("continuation_registry", {}).get("files", {}).get("resolved")
        if not isinstance(recorded_resolved, dict):
            raise RuntimeError("lineage lacks bound v11 registry resolved evidence")
        resolved_path = args.v11_registry_resolved or Path(str(recorded_resolved.get("path", "")))
        registry_resolved, resolved_binding = _load_bound_json(resolved_path, recorded_resolved)
        terminal, terminal_binding = _load_bound_json(terminal_path)
        terminal_getjob_recorded = terminal.get("raw_terminal_getjob")
        if not isinstance(terminal_getjob_recorded, dict):
            raise RuntimeError("v11 terminal lacks bound raw GetJob evidence")
        terminal_getjob, terminal_getjob_binding = _load_bound_json(
            Path(str(terminal_getjob_recorded.get("path", ""))),
            terminal_getjob_recorded,
        )
        terminal_placement_recorded = terminal.get("registry", {}).get("placement")
        if not isinstance(terminal_placement_recorded, dict):
            raise RuntimeError("v11 terminal lacks bound placement evidence")
        registry_placement, terminal_placement_binding = _load_bound_json(
            Path(str(terminal_placement_recorded.get("path", ""))),
            terminal_placement_recorded,
        )
        role_check = validate_lineage_role_separation(
            lineage,
            registry_resolved,
            terminal,
            verifier,
            terminal_getjob,
            registry_placement,
        )
        role_check["evidence"] = {
            "lineage_manifest": lineage_binding,
            "v11_registry_resolved": resolved_binding,
            "v11_terminal": terminal_binding,
            "v11_terminal_raw_getjob": terminal_getjob_binding,
            "v11_terminal_placement": terminal_placement_binding,
        }
        checks["lineage_role_separation"] = role_check
    except (OSError, ValueError, TypeError, json.JSONDecodeError, RuntimeError) as exc:
        checks["lineage_role_separation"] = {
            "pass": False,
            "errors": [str(exc)],
            "final_independent_verifier": verifier,
        }

    model_text = (experiment / "scripts/multires_policy.py").read_text()
    checks["no_privileged_model_input"] = classify_model_input_keys(model_text)

    exact = json.loads((args.formal_root / "EXACT_DATASET_AUDIT.json").read_text())
    checks["split_leakage"] = {"pass": exact["status"] == "PASS" and all(not row["split_leakage"] for row in exact["task_checks"].values()), "task_checks": exact["task_checks"]}
    preflight = json.loads((args.formal_root / "PRECHECKS.json").read_text())
    checks["unit_compile_smoke_overwrite"] = {"pass": bool(preflight.get("all_pass")), "evidence": preflight}
    training_complete = (args.training_root / "DATA_AND_TRAINING_COMPLETE.json").is_file()
    checkpoints = list(args.training_root.glob("training/*/seed_*/checkpoints/step_*/COMPLETE.json"))
    checks["shard_autoresume"] = {"pass": training_complete and len(checkpoints) >= 18 * 6, "training_complete": training_complete, "complete_checkpoint_markers": len(checkpoints)}

    bank_files = sorted((args.formal_root / "state_banks").glob("*.json"))
    pass_rates = [json.loads(path.read_text())["fidelity_pass_rate"] for path in bank_files]
    checks["fresh_reset_prefix_fidelity"] = {"pass": bool(pass_rates) and min(pass_rates) >= .95, "pass_rates": pass_rates}
    raw_files = sorted((args.formal_root / "oracle").glob("*.json"))
    row_count = utility_mismatch = accounting_missing = accounting_mismatch = 0
    for path in raw_files:
        for row in json.loads(path.read_text()).get("rows", []):
            row_count += 1
            accounting_missing += not ACCOUNTING.issubset(row["accounting"])
            accounting = row["accounting"]
            expected_flops = accounting["global_encoder_calls"] * 1.8e9 + accounting["fine_encoder_calls"] * 1.8e9 + accounting["policy_forward_calls"] * 0.7e9
            expected_latency = accounting["gpu_latency_ms"] + accounting["simulator_latency_ms"] + accounting["selector_latency_ms"]
            accounting_mismatch += abs(accounting["estimated_flops"] - expected_flops) > 1e-6
            accounting_mismatch += abs(accounting["episode_total_compute"] - expected_latency) > 1e-6
            for name, weights in WEIGHTS.items():
                expected = weights[0] * row["success_hold5"] + weights[1] * row["normalized_progress"] + weights[2] * row["recoverable"] + weights[3] * row["dropped_or_slipped"] + weights[4] * row["collision"]
                utility_mismatch += abs(expected - row["utilities"][name]) > 1e-9
    checks["raw_outcome_recompute"] = {"pass": row_count > 0 and utility_mismatch == 0, "rows": row_count, "utility_mismatches": utility_mismatch}
    statistics = json.loads((args.formal_root / "statistics.json").read_text())
    budget_mismatches = []
    for family in ("budgets", "negative_control_budgets"):
        for weight, fractions in statistics[family].items():
            for fraction, arms in fractions.items():
                expected_budget = float(fraction) * arms["all_fine"]["cost"]
                for arm, values in arms.items():
                    if not isinstance(values, dict) or "cost" not in values:
                        continue
                    observed = bool(values["cost"] <= expected_budget + 1e-6)
                    if abs(values["budget"] - expected_budget) > 1e-6 or values["budget_compliant"] != observed:
                        budget_mismatches.append(f"{family}/{weight}/{fraction}/{arm}")
    checks["compute_accounting_recompute"] = {
        "pass": row_count > 0 and accounting_missing == 0 and accounting_mismatch == 0 and not budget_mismatches,
        "missing_rows": accounting_missing,
        "formula_mismatches": accounting_mismatch,
        "budget_mismatches": budget_mismatches,
    }

    with tempfile.TemporaryDirectory(prefix="stage27r-audit-") as directory:
        recomputed = Path(directory) / "statistics.json"
        command = [str(Path(__import__("sys").executable)), str(experiment / "scripts/analyze_stage27r.py"), "--inputs", *map(str, raw_files), "--output", str(recomputed)]
        subprocess.run(command, check=True, cwd=experiment / "scripts")
        expected_stats = args.formal_root / "statistics.json"
        checks["paired_statistics_recompute"] = {"pass": sha256_file(recomputed) == sha256_file(expected_stats), "recomputed_sha256": sha256_file(recomputed), "reported_sha256": sha256_file(expected_stats)}

    manifest = official_scientific_manifest(args.formal_root, args.output)
    checks["scientific_sha256_manifest"] = {"pass": bool(manifest), "files": len(manifest)}
    checks["all_pass"] = all(value["pass"] for value in checks.values() if isinstance(value, dict) and "pass" in value)
    atomic_json(args.output, {"protocol_id": PROTOCOL_ID, "checks": checks, "manifest": manifest})
    print(json.dumps(checks, indent=2))


if __name__ == "__main__":
    main()
